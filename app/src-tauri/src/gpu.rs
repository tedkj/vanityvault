//! The GPU key engine (OpenCL).
//!
//! The graphics card runs the whole chain for millions of keys at a time: seed, SHA-512, ed25519
//! public key, base58 address, pattern check. It only reports the seeds whose address matched.
//!
//! Nothing the card says is trusted. At startup it derives 1024 keys that the CPU then derives
//! again and compares byte for byte, and the engine derives every reported match again on the CPU
//! before keeping it. A wrong driver or a broken card can waste time; it cannot produce a bad key.
//!
//! Where the keys come from: for every batch the operating system's random source gives 24 fresh
//! bytes. Each key in the batch is those 24 bytes followed by an 8-byte counter, so every key
//! carries 192 random bits that never leave this PC.
//!
//! The program in `kernel/grind.cl` and the table in `kernel/comb.bin` are generated by
//! `kernel/gen/make.py`.

use std::ffi::c_void;
use std::ptr;
use std::time::Instant;

use ed25519_dalek::SigningKey;
use opencl3::command_queue::CommandQueue;
use opencl3::context::Context;
use opencl3::device::{Device, CL_DEVICE_TYPE_GPU};
use opencl3::kernel::{ExecuteKernel, Kernel};
use opencl3::memory::{Buffer, CL_MEM_COPY_HOST_PTR, CL_MEM_READ_ONLY, CL_MEM_READ_WRITE};
use opencl3::platform::get_platforms;
use opencl3::program::Program;
use opencl3::types::CL_BLOCKING;
use rand_core::{OsRng, RngCore};
use sha2::{Digest, Sha512};
use zeroize::Zeroizing;

use crate::list::{Packed, PACKED_LEN};
use crate::pattern::Pattern;

const SOURCE: &str = include_str!("../kernel/grind.cl");
const COMB: &[u8] = include_bytes!("../kernel/comb.bin");

// These mirror the #defines in grind.cl.
const K: usize = 32;
const MAX_MATCHES: usize = 256;
const MATCH_STRIDE: usize = 112;
const MAX_PAT: usize = 16;
const PAT_STRIDE: usize = 2 + 2 * MAX_PAT;
const SELFTEST_ROW: usize = 141;

/// Work items per batch, each making K keys. The engine starts small and grows until a batch
/// takes long enough to be efficient but short enough that Stop and the rest of the desktop stay
/// responsive.
const ITEMS_START: usize = 1 << 13;
const ITEMS_MIN: usize = 1 << 10;
const ITEMS_MAX: usize = 1 << 21;
const BATCH_MS_LOW: u128 = 40;
const BATCH_MS_HIGH: u128 = 160;

pub type Seed = Zeroizing<[u8; 32]>;

pub struct Gpu {
    pub name: String,
    grind: Kernel,
    base: Buffer<u8>,
    count: Buffer<u32>,
    found: Buffer<u8>,
    comb: Buffer<i32>,
    pats: Buffer<u8>,
    list: Buffer<u32>,
    /// How many main patterns, start words and end words the card checks.
    npat: u32,
    starts: u32,
    ends: u32,
    any_case: u32,
    items: usize,
    local: usize,
    queue: CommandQueue,
    _program: Program,
    _context: Context,
}

fn cl<T>(r: opencl3::Result<T>) -> Result<T, String> {
    r.map_err(|e| format!("graphics card error: {e}"))
}

/// The card to use: a separate graphics card beats one built into the processor, then more memory wins.
fn pick() -> Result<Device, String> {
    let mut best: Option<(u64, Device)> = None;
    for platform in get_platforms().map_err(|_| "no graphics driver with OpenCL on this PC")? {
        for id in platform.get_devices(CL_DEVICE_TYPE_GPU).unwrap_or_default() {
            let device = Device::new(id);
            let vendor = device.vendor().unwrap_or_default().to_lowercase();
            let separate = vendor.contains("nvidia") || vendor.contains("advanced micro") || vendor.contains("amd");
            let score = ((separate as u64) << 62) | (device.global_mem_size().unwrap_or(0) >> 2);
            if best.as_ref().map_or(true, |(s, _)| score > *s) {
                best = Some((score, device));
            }
        }
    }
    best.map(|(_, d)| d).ok_or_else(|| "no graphics card found".into())
}

impl Gpu {
    /// Finds a card, builds the program for it and proves it against the CPU.
    pub fn open() -> Result<Self, String> {
        let device = pick()?;
        let name = device.name().unwrap_or_default().trim().to_string();
        let context = cl(Context::from_device(&device))?;
        // The 1.x call on purpose: it exists on every driver, old and new.
        #[allow(deprecated)]
        let queue = cl(unsafe { CommandQueue::create(&context, device.id(), 0) })?;
        let program = Program::create_and_build_from_source(&context, SOURCE, "-cl-std=CL1.2")
            .map_err(|log| format!("the graphics driver could not build the key program: {log}"))?;
        let grind = cl(Kernel::create(&program, "grind"))?;

        let mut table: Vec<i32> = COMB.chunks_exact(4).map(|b| i32::from_le_bytes([b[0], b[1], b[2], b[3]])).collect();
        let comb = cl(unsafe {
            Buffer::<i32>::create(&context, CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR, table.len(), table.as_mut_ptr() as *mut c_void)
        })?;
        let buf = |n: usize| cl(unsafe { Buffer::<u8>::create(&context, CL_MEM_READ_WRITE, n, ptr::null_mut()) });
        let base = buf(24)?;
        let found = buf(MAX_MATCHES * MATCH_STRIDE)?;
        let pats = buf(PAT_STRIDE)?;
        let count = cl(unsafe { Buffer::<u32>::create(&context, CL_MEM_READ_WRITE, 1, ptr::null_mut()) })?;
        let list = cl(unsafe { Buffer::<u32>::create(&context, CL_MEM_READ_WRITE, PACKED_LEN, ptr::null_mut()) })?;

        // Work groups of 128 suit the kernel; older drivers need the batch to be a multiple of it.
        let local = device.max_work_group_size().unwrap_or(1).clamp(1, 128);
        let local = if local.is_power_of_two() { local } else { local.next_power_of_two() / 2 };

        let gpu = Self { name, grind, base, count, found, comb, pats, list, npat: 0, starts: 0, ends: 0, any_case: 0, items: ITEMS_START, local, queue, _program: program, _context: context };
        gpu.selftest()?;
        Ok(gpu)
    }

    /// 1024 keys made on the card and again on the CPU must agree in every byte.
    fn selftest(&self) -> Result<(), String> {
        const N: usize = 1024;
        let mut seeds = vec![0u8; N * 32];
        // The first key stays all zeros, a published test value; the rest are random.
        OsRng.fill_bytes(&mut seeds[32..]);
        let mut out = vec![0u8; N * SELFTEST_ROW];
        let kernel = cl(Kernel::create(&self._program, "selftest"))?;
        unsafe {
            let seed_buf = cl(Buffer::<u8>::create(
                &self._context,
                CL_MEM_READ_ONLY | CL_MEM_COPY_HOST_PTR,
                seeds.len(),
                seeds.as_mut_ptr() as *mut c_void,
            ))?;
            let out_buf = cl(Buffer::<u8>::create(&self._context, CL_MEM_READ_WRITE, out.len(), ptr::null_mut()))?;
            cl(ExecuteKernel::new(&kernel)
                .set_arg(&seed_buf)
                .set_arg(&out_buf)
                .set_arg(&(N as u32))
                .set_arg(&self.comb)
                .set_global_work_size(N / K)
                .enqueue_nd_range(&self.queue))?;
            cl(self.queue.enqueue_read_buffer(&out_buf, CL_BLOCKING, 0, &mut out, &[]))?;
        }
        for (seed, row) in seeds.chunks_exact(32).zip(out.chunks_exact(SELFTEST_ROW)) {
            let seed: &[u8; 32] = seed.try_into().unwrap();
            let public = SigningKey::from_bytes(seed).verifying_key().to_bytes();
            let address = bs58::encode(public).into_string();
            let len = row[96] as usize;
            let same = row[..64] == Sha512::digest(seed)[..]
                && row[64..96] == public
                && len <= 44
                && &row[97..97 + len] == address.as_bytes();
            if !same {
                return Err("the graphics card gave a wrong answer in the startup check".into());
            }
        }
        Ok(())
    }

    /// The main pattern, or none when only the hunt list is in play.
    pub fn set_pattern(&mut self, pat: Option<&Pattern>) -> Result<(), String> {
        self.npat = pat.is_some() as u32;
        let Some(pat) = pat else { return Ok(()) };
        let mut row = [0u8; PAT_STRIDE];
        let lower = |c: &u8| if pat.any_case { c.to_ascii_lowercase() } else { *c };
        row[0] = pat.start.len() as u8;
        row[1] = pat.end.len() as u8;
        for (i, c) in pat.start.iter().enumerate() {
            row[2 + i] = lower(c);
        }
        for (i, c) in pat.end.iter().enumerate() {
            row[2 + MAX_PAT + i] = lower(c);
        }
        self.any_case = pat.any_case as u32;
        cl(unsafe { self.queue.enqueue_write_buffer(&mut self.pats, CL_BLOCKING, 0, &row, &[]) })?;
        Ok(())
    }

    /// The hunt list's lookup table, or none to switch the list off.
    pub fn set_list(&mut self, packed: Option<&Packed>) -> Result<(), String> {
        (self.starts, self.ends) = packed.map_or((0, 0), |p| (p.starts as u32, p.ends as u32));
        if let Some(p) = packed {
            cl(unsafe { self.queue.enqueue_write_buffer(&mut self.list, CL_BLOCKING, 0, &p.data, &[]) })?;
        }
        Ok(())
    }

    /// Makes and checks one batch of keys. Returns how many were tried and the seeds whose
    /// address the card says matched.
    pub fn batch(&mut self) -> Result<(u64, Vec<Seed>), String> {
        let t0 = Instant::now();
        let items = self.items;
        let mut base = Zeroizing::new([0u8; 24]);
        OsRng.fill_bytes(&mut base[..]);
        let mut count = [0u32];
        unsafe {
            cl(self.queue.enqueue_write_buffer(&mut self.base, CL_BLOCKING, 0, &base[..], &[]))?;
            cl(self.queue.enqueue_write_buffer(&mut self.count, CL_BLOCKING, 0, &count, &[]))?;
            cl(ExecuteKernel::new(&self.grind)
                .set_arg(&self.base)
                .set_arg(&0u64)
                .set_arg(&(K as u32))
                .set_arg(&self.count)
                .set_arg(&self.found)
                .set_arg(&self.comb)
                .set_arg(&self.pats)
                .set_arg(&self.npat)
                .set_arg(&self.any_case)
                .set_arg(&self.list)
                .set_arg(&self.starts)
                .set_arg(&self.ends)
                .set_global_work_size(items)
                .set_local_work_size(self.local)
                .enqueue_nd_range(&self.queue))?;
            cl(self.queue.enqueue_read_buffer(&self.count, CL_BLOCKING, 0, &mut count, &[]))?;
        }

        let mut seeds = Vec::new();
        let n = (count[0] as usize).min(MAX_MATCHES);
        if n > 0 {
            let mut rows = Zeroizing::new(vec![0u8; n * MATCH_STRIDE]);
            unsafe {
                cl(self.queue.enqueue_read_buffer(&self.found, CL_BLOCKING, 0, &mut rows[..], &[]))?;
                // Wipe the matches on the card once they are read.
                let zeros = vec![0u8; n * MATCH_STRIDE];
                cl(self.queue.enqueue_write_buffer(&mut self.found, CL_BLOCKING, 0, &zeros, &[]))?;
            }
            for row in rows.chunks_exact(MATCH_STRIDE) {
                let mut seed = Zeroizing::new([0u8; 32]);
                seed.copy_from_slice(&row[..32]);
                seeds.push(seed);
            }
        }

        let ms = t0.elapsed().as_millis();
        if ms < BATCH_MS_LOW && self.items < ITEMS_MAX {
            self.items *= 2;
        } else if ms > BATCH_MS_HIGH && self.items > ITEMS_MIN.max(self.local) {
            self.items /= 2;
        }
        Ok(((items * K) as u64, seeds))
    }
}
